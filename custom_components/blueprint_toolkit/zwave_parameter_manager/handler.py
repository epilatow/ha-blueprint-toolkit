def _resolve_config_path(hass: HomeAssistant, config_file_path: str) -> str:
    if os.path.isabs(config_file_path):
        return config_file_path
    return os.path.join(hass.config.config_dir, config_file_path)


def _read_mtime(path: str) -> float:
    """Return mtime, or 0.0 if the file is missing."""
    try:
        return os.path.getmtime(path)
    except OSError:
        return 0.0


def _read_text(path: str) -> tuple[str, str | None]:
    """Read the policy YAML file. Returns (text, error_or_None).

    A missing file is not an error: it means no policies yet.
    """
    try:
        with open(path, encoding="utf-8") as f:
            return f.read(), None
    except FileNotFoundError:
        return "", None
    except OSError as err:
        return "", f"could not read config file: {err}"


def _load_mapping() -> tuple[zpm_logic.MappingTable | None, str | None]:
    """Load + parse the shipped mapping.json. Returns (table, error)."""
    try:
        raw = json.loads(Path(_MAPPING_PATH).read_text(encoding="utf-8"))
    except (OSError, ValueError) as err:
        return None, f"could not read mapping.json: {err}"
    try:
        return zpm_logic.MappingTable.from_dict(raw), None
    except (ValueError, KeyError, TypeError) as err:
        return None, f"invalid mapping.json: {err}"


